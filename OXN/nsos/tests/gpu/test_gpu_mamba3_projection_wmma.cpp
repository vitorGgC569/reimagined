int main() {
    return gpu_parity_test::run_parity("mamba3_projection_wmma",[] {
        set_matmul_precision_mode(0);
        for(auto mode:{mp::Policy::BF16,mp::Policy::FP16}) {
            require(mp::supported(mode),"RDNA3 WMMA build/device unavailable");
            for(auto flags:{std::pair{false,false},std::pair{false,true},std::pair{true,false},std::pair{true,true}})
                for(auto dims:{std::array<int,3>{1,1,1},std::array<int,3>{17,33,35},std::array<int,3>{65,47,63}})
                    raw_gemm(mode,flags.first,flags.second,dims[0],dims[1],dims[2]);
            for(auto flags:{std::pair{false,false},std::pair{false,true},std::pair{true,false},std::pair{true,true}}) {
                raw_gemm(mode,flags.first,flags.second,17,33,35,mp::ExactAxis::OutputRows,13);
                raw_gemm(mode,flags.first,flags.second,17,33,35,mp::ExactAxis::OutputCols,29);
                raw_gemm(mode,flags.first,flags.second,17,33,35,mp::ExactAxis::Reduction,31);
            }
            for(auto flags:{std::pair{false,false},std::pair{false,true},std::pair{true,false},std::pair{true,true}})
                for(auto dims:{std::array<int,3>{1,1,1},std::array<int,3>{33,9,65},std::array<int,3>{65,19,513}})
                    for(auto axis:{mp::ExactAxis::OutputRows,mp::ExactAxis::OutputCols,mp::ExactAxis::Reduction}) {
                        const int extent=axis==mp::ExactAxis::OutputRows?dims[0]:axis==mp::ExactAxis::OutputCols?dims[1]:dims[2];
                        for(int begin:{0,std::min(31,extent-1),extent-1}) controltail_order(mode,flags.first,flags.second,dims[0],dims[1],dims[2],axis,begin);
                    }
            full_layer(mode,false,false);full_layer(mode,true,true);continuation(mode);
        }
        failure_and_policy();env(nullptr);
        gpu_parity_test::cuda_sync_or_throw("Mamba3 WMMA completion");
    });
}
